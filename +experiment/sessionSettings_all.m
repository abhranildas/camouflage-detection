function SessionSettings = sessionSettings_all(luminance, contrast, stimulus_size, ...
    target_radius, ppd)
% SESSIONSETTINGS_ALL  Settings and stimuli for the all-textures experiment variant.
%   SessionSettings = experiment.sessionSettings_all(luminance, contrast, ...
%       stimulus_size, target_radius, ppd)
%
%   Variant of experiment.sessionSettings whose levels are textures rather
%   than edge-power bands. Loads the texture list, generates the same number
%   of trials for each texture, and shuffles them into the usual
%   trial/level/session layout. There is no edge-power file, so no
%   edgePowerBlockEdges and no edgePowers; instead the per-trial texture is
%   recorded in .textures.
%
%   Inputs
%     luminance     - mean luminance, normalised, in [0, 1].
%     contrast      - RMS contrast, dimensionless fraction.
%     stimulus_size - stimulus side, in pixels.
%     target_radius - target radius, in pixels.
%     ppd           - pixels per degree. Stored in the .monitor_distance
%                     field, which is a misnomer shared with the base variant
%                     (B3.8); here at least the local says what it holds.
%
%   Output
%     SessionSettings - the ExpSettings struct, as in experiment.
%                       sessionSettings but with .textures, .nTex and
%                       .nTrials_eachtx in place of the edge-power fields.
%
%   The trial count is derived, not chosen: nTex textures x 40 trials each,
%   redistributed over 10 levels and 4 sessions.
%
%   Every field name here is serialised into exp_settings.mat, so none may be
%   renamed without a migration (zone 3, S3.10) — including the misspelled
%   .moniter_brightness and the local responseInvervalMs that feeds
%   .responseIntervalMs, which keeps its typo because the corrected name would
%   equal a string literal in this file.
%
%   This is one of five near-duplicate sessionSettings variants; S3.3
%   collapses them.
%
%   See also experiment.SETUPEXPERIMENT_ALL, experiment.GENERATE_CAMOUFLAGE_STIMULI_ALL,
%   experiment.SESSIONSETTINGS.

    stimulusIntervalMs = 200;
    responseInvervalMs = 1000;
    fixationIntervalMs = 100;
    blankIntervalMs = 0;

    monitorMaxPix = 255;
    bgPixVal = luminance*255;
    monitor_brightness = 50;
    monitor_contrast = 100;

    % load texture list
    load('exp_files/all/texture_list.mat');
    nTex = length(texture_list);

    nTrials_eachtx = 40;

    nLevels = 10;
    nSessions = 4;
    nTrials = nTex*nTrials_eachtx/(nLevels*nSessions);

    stimPosDeg = zeros(nTrials, nLevels, nSessions, 2);
    fixPosDeg = zeros(nTrials, nLevels, nSessions, 2);

    loadSessionStimuli = @experiment.loadStimuliCamouflage;
    pTarget = .5;

    % generate stimuli
    [stimuli, textures, seeds, bTargetPresent, pClipped] = ...
        experiment.generate_camouflage_stimuli_all(texture_list, nTex, nTrials_eachtx, ...
        nTrials, nLevels, nSessions, stimulus_size, target_radius, luminance, contrast);

    SessionSettings = struct(...
        'exp_type', 'all',...
        'textures', textures,...
        'luminance', luminance,...
        'contrast', contrast,...
        'target_radius', target_radius,...
        'stimulus_size', stimulus_size,...
        'monitor_distance', ppd,...
        'nTrials_eachtx', nTrials_eachtx,...
        'nLevels', nLevels,...
        'nTex', nTex,...
        'nTrials', nTrials,...
        'nSessions', nSessions, ...
        'pTarget', pTarget,...
        'loadSessionStimuli', loadSessionStimuli, ...
        'bTargetPresent', bTargetPresent,...
        'seeds', seeds,...
        'stimuli', stimuli,...
        'pClipped', pClipped,...
        'moniter_brightness', monitor_brightness,...
        'monitor_contrast', monitor_contrast,...
        'stimPosDeg', stimPosDeg, ...
        'fixPosDeg', fixPosDeg,...
        'monitorMaxPix', monitorMaxPix, ...
        'bgPixVal', bgPixVal, ...
        'stimulusIntervalMs', stimulusIntervalMs,...
        'responseIntervalMs', responseInvervalMs, ...
        'fixationIntervalMs', fixationIntervalMs,...
        'blankIntervalMs', blankIntervalMs...
        );
end
