function SessionSettings = session_settings_texture_exponent(exp_type, texture, ...
    texture_exponents, ml, cont, bg_size, target_radius, monitor_distance)
% SESSION_SETTINGS_TEXTURE_EXPONENT  Settings and stimuli for the texture-exponent variant.
%   SessionSettings = experiment.session_settings_texture_exponent(exp_type, texture, ...
%       texture_exponents, ml, cont, bg_size, target_radius, monitor_distance)
%
%   Variant of experiment.session_settings whose levels are texture 1/f
%   exponents rather than edge-power bands: one level is one exponent, applied
%   to target and background alike. Edge power is measured from each stimulus
%   after it is made, so there are no edge_power_block_edges.
%
%   Inputs
%     exp_type          - experiment name, also the exp_files/ subdirectory.
%     texture           - texture struct for lib.stimulus (.type). The
%                         generator builds its own copy rather than using this
%                         one; this copy is only stored in the settings.
%     texture_exponents - texture 1/f exponent per level, dimensionless.
%     ml                - mean luminance, normalised, in [0, 1].
%     cont              - RMS contrast, dimensionless fraction.
%     bg_size           - stimulus side, in pixels.
%     target_radius     - target radius, in pixels.
%     monitor_distance  - misnamed: pixels per degree, not a distance (B3.8).
%
%   Output
%     SessionSettings - the ExpSettings struct, as in experiment.
%                       session_settings but with .alphas in place of
%                       .edgePowerBlockEdges, and with the level count and
%                       seeds stored under .nBlocks and .stimuliSeed.
%
%   Those last two names are the regression B2.6 records: every consumer of
%   this settings file — experiment.subject_experiment_file,
%   experiment.load_stimuli_camouflage and
%   experiment.analysis.compute_threshold_texture_exponent — reads .nLevels and
%   .seeds, which this variant alone stops emitting. The settings file on disk
%   still has .nLevels, so it was written by an earlier version of this file.
%
%   The texture exponents are stored in a field named .alphas, which the shape-
%   exponent variant uses for a different quantity (a boundary shape
%   exponent). The local is named texture_exponents throughout this family to
%   keep the two apart; the field name is frozen on disk (zone 3, S3.10).
%
%   ml and cont keep their abbreviated names, unlike the base variant's
%   luminance/contrast, because the corrected names would equal the
%   'luminance' and 'contrast' field-name string literals in the struct call
%   below — a rename Stage 1 cannot make.
%
%   This is one of five near-duplicate session_settings variants; S3.3
%   collapses them.
%
%   See also experiment.SET_UP_EXPERIMENT_TEXTURE_EXPONENT,
%   experiment.GENERATE_CAMOUFLAGE_STIMULI_TEXTURE_EXPONENT, experiment.SESSION_SETTINGS.

    stimulus_interval_ms = 200;
    response_interval_ms = 1000;
    fixation_interval_ms = 100;
    blank_interval_ms = 0;

    monitor_max_pix = 255;
    bg_pix_val = ml*255;
    monitor_brightness = 50;
    monitor_contrast = 100;

    n_blocks = length(texture_exponents);
    n_trials = 30;
    n_sessions = 4;

    stim_pos_deg = zeros(n_trials, n_blocks, n_sessions, 2);
    fix_pos_deg = zeros(n_trials, n_blocks, n_sessions, 2);

    load_session_stimuli = @experiment.load_stimuli_camouflage;
    p_target = .5;

    % generate stimuli
    b_target_present = logical(experiment.generate_target_present_matrix(n_trials, n_blocks, ...
        n_sessions, p_target));
    [stimuli, stimuli_seed, stim_edge_powers, p_clipped] = ...
        experiment.generate_camouflage_stimuli_texture_exponent(texture_exponents, n_trials, ...
        n_sessions, bg_size, target_radius, ml, cont, b_target_present);

    SessionSettings = struct(...
        'exp_type', exp_type,...
        'texture_params', texture,...
        'alphas', texture_exponents,...
        'luminance', ml,...
        'contrast', cont,...
        'target_radius', target_radius,...
        'stimulus_size', bg_size,...
        'monitor_distance', monitor_distance,...
        'nBlocks', n_blocks,...
        'nTrials', n_trials,...
        'nSessions', n_sessions, ...
        'pTarget', p_target,...
        'loadSessionStimuli', load_session_stimuli, ...
        'bTargetPresent', b_target_present,...
        'edgePowers', stim_edge_powers,...
        'stimuliSeed', stimuli_seed,...
        'stimuli', stimuli,...
        'pClipped', p_clipped,...
        'moniter_brightness', monitor_brightness,...
        'monitor_contrast', monitor_contrast,...
        'stimPosDeg', stim_pos_deg, ...
        'fixPosDeg', fix_pos_deg,...
        'monitorMaxPix', monitor_max_pix, ...
        'bgPixVal', bg_pix_val, ...
        'stimulusIntervalMs', stimulus_interval_ms,...
        'responseIntervalMs', response_interval_ms, ...
        'fixationIntervalMs', fixation_interval_ms,...
        'blankIntervalMs', blank_interval_ms...
        );
end
