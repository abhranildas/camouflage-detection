function SessionSettings = session_settings(exp_type, texture_params, luminance, contrast, ...
    stimulus_size, target_radius, edgePowerBlockEdges, monitor_distance, transformExpName)
% SESSION_SETTINGS  Build the complete settings and stimulus set for one experiment.
%   SessionSettings = experiment.session_settings(exp_type, texture_params, luminance, ...
%       contrast, stimulus_size, target_radius, edgePowerBlockEdges, ...
%       monitor_distance, transformExpName)
%
%   Fixes the trial structure and display timings, then either synthesises a
%   fresh stimulus set with experiment.generate_camouflage_stimuli or, if
%   transformExpName names an existing experiment, rescales that experiment's
%   stimuli to the new luminance and contrast instead. The returned struct is
%   what gets saved as ExpSettings and is the only record of how an experiment
%   was configured.
%
%   Inputs
%     exp_type            - experiment name, also the exp_files/ subdirectory.
%     texture_params      - texture struct for lib.stimulus: .type, and
%                           .stats/.Niter for a Portilla-Simoncelli texture.
%     luminance           - mean luminance, normalised, in [0, 1].
%     contrast            - RMS contrast, dimensionless fraction.
%     stimulus_size       - stimulus side, in pixels.
%     target_radius       - target radius, in pixels.
%     edgePowerBlockEdges - nLevels x 2 array of [lower, upper] edge-power
%                           limits per level, dimensionless edge power.
%     monitor_distance    - misnamed: pixels per degree, not a distance (B3.8).
%     transformExpName    - name of an experiment whose stimuli to rescale,
%                           or '' to synthesise new ones.
%
%   Output
%     SessionSettings - the ExpSettings struct: the inputs above, the trial
%                       structure (.nLevels, .nTrials = 30, .nSessions = 4,
%                       .pTarget), the stimuli and their .seeds, .edgePowers
%                       and .pClipped, the display settings (.monitorMaxPix
%                       and .bgPixVal in 8-bit pixel values, monitor
%                       brightness and contrast in percent) and the four
%                       interval durations in milliseconds.
%
%   Every field name here is serialised into exp_settings.mat and read back by
%   the runtime and the analysis, so none may be renamed without a migration
%   (zone 3, S3.10). Two of them are already misspelled and frozen that way:
%   .moniter_brightness, and the local responseInvervalMs feeding
%   .responseIntervalMs. The local keeps the typo because correcting it would
%   make it equal the field-name string literal in the same file, which Stage
%   1 cannot do.
%
%   .nSessions is 4 and .nTrials 30, so a full experiment is 30 x nLevels x 4
%   trials per subject.
%
%   The guard on transformExpName carries a stray transpose, strcmp(x', ''),
%   which happens to behave the same way for a character row vector (B3.7).
%
%   See also experiment.SET_UP_EXPERIMENT, experiment.GENERATE_CAMOUFLAGE_STIMULI,
%   experiment.TRANSFORM_CAMOUFLAGE_STIMULI, experiment.LOAD_STIMULI_CAMOUFLAGE.

    stimulusIntervalMs = 200;
    responseInvervalMs = 1000;
    fixationIntervalMs = 100;
    blankIntervalMs = 0;

    monitorMaxPix = 255;
    bgPixVal = luminance*255;
    monitor_brightness = 50;
    monitor_contrast = 100;

    nLevels = size(edgePowerBlockEdges, 1);
    nTrials = 30;
    nSessions = 4;

    % edgePowerBlockCenters=movmean(edgePowerBlockEdges,2,'Endpoints','discard');
    edgePowerBlockCenters = mean(edgePowerBlockEdges, 2);

    stimPosDeg = zeros(nTrials, nLevels, nSessions, 2);
    fixPosDeg = zeros(nTrials, nLevels, nSessions, 2);

    loadSessionStimuli = @experiment.load_stimuli_camouflage;
    pTarget = .5;

    if strcmp(transformExpName', '')
        % generate new stimuli
        bTargetPresent = logical(experiment.generate_target_present_matrix(nTrials, nLevels, ...
            nSessions, pTarget));
        [stimuli, seeds, edgePowers, pClipped] = experiment.generate_camouflage_stimuli(...
            texture_params, exp_type, edgePowerBlockEdges, nTrials, nSessions, ...
            stimulus_size, target_radius, luminance, contrast, bTargetPresent);
    else
        % transform stimuli of existing experiment
        [stimuli, seeds, edgePowers, pClipped, bTargetPresent] = ...
            experiment.transform_camouflage_stimuli(transformExpName, luminance, contrast);
    end

    SessionSettings = struct(...
        'exp_type', exp_type,...
        'texture_params', texture_params,...
        'luminance', luminance,...
        'contrast', contrast,...
        'target_radius', target_radius,...
        'stimulus_size', stimulus_size,...
        'monitor_distance', monitor_distance,...
        'nLevels', nLevels,...
        'nTrials', nTrials,...
        'nSessions', nSessions, ...
        'pTarget', pTarget,...
        'loadSessionStimuli', loadSessionStimuli, ...
        'bTargetPresent', bTargetPresent,...
        'edgePowerBlockEdges', edgePowerBlockEdges,...
        'edgePowerBlockCenters', edgePowerBlockCenters,...
        'edgePowers', edgePowers,...
        'seeds', seeds,...
        'stimuli', stimuli,...
        'pClipped', pClipped,...
        'moniter_brightness', monitor_brightness,...
        'monitor_contrast', monitor_contrast,...
        'stimPosDeg', stimPosDeg, ...
        'fixPosDeg', fixPosDeg,...
        'monitorMaxPix', monitorMaxPix, ...
        'bgPixVal', bgPixVal, ...
        'stimulusIntervalMs', stimulusIntervalMs,...
        'responseIntervalMs', responseInvervalMs, ...
        'fixationIntervalMs', fixationIntervalMs,...
        'blankIntervalMs', blankIntervalMs...
        );
end
