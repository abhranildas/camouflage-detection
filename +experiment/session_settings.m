function SessionSettings = session_settings(exp_type, texture_params, luminance, contrast, ...
    stimulus_size, target_radius, edge_power_block_edges, monitor_distance, transform_exp_name)
% SESSION_SETTINGS  Build the complete settings and stimulus set for one experiment.
%   SessionSettings = experiment.session_settings(exp_type, texture_params, luminance, ...
%       contrast, stimulus_size, target_radius, edge_power_block_edges, ...
%       monitor_distance, transform_exp_name)
%
%   Fixes the trial structure and display timings, then either synthesises a
%   fresh stimulus set with experiment.generate_camouflage_stimuli or, if
%   transform_exp_name names an existing experiment, rescales that experiment's
%   stimuli to the new luminance and contrast instead. The returned struct is
%   what gets saved as ExpSettings and is the only record of how an experiment
%   was configured.
%
%   Inputs
%     exp_type               - experiment name, also the exp_files/ subdirectory.
%     texture_params         - texture struct for lib.stimulus: .type, and
%                              .stats/.Niter for a Portilla-Simoncelli texture.
%     luminance              - mean luminance, normalised, in [0, 1].
%     contrast               - RMS contrast, dimensionless fraction.
%     stimulus_size          - stimulus side, in pixels.
%     target_radius          - target radius, in pixels.
%     edge_power_block_edges - n_levels x 2 array of [lower, upper] edge-power
%                              limits per level, dimensionless edge power.
%     monitor_distance       - misnamed: pixels per degree, not a distance (B3.8).
%     transform_exp_name     - name of an experiment whose stimuli to rescale,
%                              or '' to synthesise new ones.
%
%   Output
%     SessionSettings - the ExpSettings struct: the inputs above, the trial
%                       structure (.nLevels, .nTrials = 30, .nSessions = 4,
%                       .pTarget), the stimuli and their .seeds, .edgePowers
%                       and .pClipped, the display settings (.monitorMaxPix
%                       and .bgPixVal in 8-bit pixel values, monitor
%                       brightness and contrast in percent) and the four
%                       interval durations in milliseconds.
%
%   Every field name here is serialised into exp_settings.mat and read back by
%   the runtime and the analysis, so none may be renamed without a migration
%   (zone 3, S3.10). One of them is already misspelled and frozen that way:
%   .moniter_brightness. The local feeding .responseIntervalMs was misspelled
%   too (responseInvervalMs), only so that it could not collide with the
%   field-name string literal in the same file; snake_casing it to
%   response_interval_ms (S2.19) dissolved the collision and the typo with it.
%
%   .nSessions is 4 and .nTrials 30, so a full experiment is 30 x n_levels x 4
%   trials per subject.
%
%   The guard on transform_exp_name carries a stray transpose, strcmp(x', ''),
%   which happens to behave the same way for a character row vector (B3.7).
%
%   See also experiment.SET_UP_EXPERIMENT, experiment.GENERATE_CAMOUFLAGE_STIMULI,
%   experiment.TRANSFORM_CAMOUFLAGE_STIMULI, experiment.LOAD_STIMULI_CAMOUFLAGE.

    stimulus_interval_ms = 200;
    response_interval_ms = 1000;
    fixation_interval_ms = 100;
    blank_interval_ms = 0;

    monitor_max_pix = 255;
    bg_pix_val = luminance*255;
    monitor_brightness = 50;
    monitor_contrast = 100;

    n_levels = size(edge_power_block_edges, 1);
    n_trials = 30;
    n_sessions = 4;

    % edge_power_block_centers=movmean(edge_power_block_edges,2,'Endpoints','discard');
    edge_power_block_centers = mean(edge_power_block_edges, 2);

    stim_pos_deg = zeros(n_trials, n_levels, n_sessions, 2);
    fix_pos_deg = zeros(n_trials, n_levels, n_sessions, 2);

    load_session_stimuli = @experiment.load_stimuli_camouflage;
    p_target = .5;

    if strcmp(transform_exp_name', '')
        % generate new stimuli
        b_target_present = logical(experiment.generate_target_present_matrix(n_trials, n_levels, ...
            n_sessions, p_target));
        [stimuli, seeds, stim_edge_powers, p_clipped] = experiment.generate_camouflage_stimuli(...
            texture_params, exp_type, edge_power_block_edges, n_trials, n_sessions, ...
            stimulus_size, target_radius, luminance, contrast, b_target_present);
    else
        % transform stimuli of existing experiment
        [stimuli, seeds, stim_edge_powers, p_clipped, b_target_present] = ...
            experiment.transform_camouflage_stimuli(transform_exp_name, luminance, contrast);
    end

    SessionSettings = struct(...
        'exp_type', exp_type,...
        'texture_params', texture_params,...
        'luminance', luminance,...
        'contrast', contrast,...
        'target_radius', target_radius,...
        'stimulus_size', stimulus_size,...
        'monitor_distance', monitor_distance,...
        'nLevels', n_levels,...
        'nTrials', n_trials,...
        'nSessions', n_sessions, ...
        'pTarget', p_target,...
        'loadSessionStimuli', load_session_stimuli, ...
        'bTargetPresent', b_target_present,...
        'edgePowerBlockEdges', edge_power_block_edges,...
        'edgePowerBlockCenters', edge_power_block_centers,...
        'edgePowers', stim_edge_powers,...
        'seeds', seeds,...
        'stimuli', stimuli,...
        'pClipped', p_clipped,...
        'moniter_brightness', monitor_brightness,...
        'monitor_contrast', monitor_contrast,...
        'stimPosDeg', stim_pos_deg, ...
        'fixPosDeg', fix_pos_deg,...
        'monitorMaxPix', monitor_max_pix, ...
        'bgPixVal', bg_pix_val, ...
        'stimulusIntervalMs', stimulus_interval_ms,...
        'responseIntervalMs', response_interval_ms, ...
        'fixationIntervalMs', fixation_interval_ms,...
        'blankIntervalMs', blank_interval_ms...
        );
end
