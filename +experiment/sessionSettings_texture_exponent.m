function SessionSettings = sessionSettings_texture_exponent(exp_type, texture, ...
    texture_exponents, ml, cont, bg_size, target_radius, monitor_distance)
% SESSIONSETTINGS_TEXTURE_EXPONENT  Settings and stimuli for the texture-exponent variant.
%   SessionSettings = experiment.sessionSettings_texture_exponent(exp_type, texture, ...
%       texture_exponents, ml, cont, bg_size, target_radius, monitor_distance)
%
%   Variant of experiment.sessionSettings whose levels are texture 1/f
%   exponents rather than edge-power bands: one level is one exponent, applied
%   to target and background alike. Edge power is measured from each stimulus
%   after it is made, so there are no edgePowerBlockEdges.
%
%   Inputs
%     exp_type          - experiment name, also the exp_files/ subdirectory.
%     texture           - texture struct for lib.stimulus (.type). The
%                         generator builds its own copy rather than using this
%                         one; this copy is only stored in the settings.
%     texture_exponents - texture 1/f exponent per level, dimensionless.
%     ml                - mean luminance, normalised, in [0, 1].
%     cont              - RMS contrast, dimensionless fraction.
%     bg_size           - stimulus side, in pixels.
%     target_radius     - target radius, in pixels.
%     monitor_distance  - misnamed: pixels per degree, not a distance (B3.8).
%
%   Output
%     SessionSettings - the ExpSettings struct, as in experiment.
%                       sessionSettings but with .alphas in place of
%                       .edgePowerBlockEdges, and with the level count and
%                       seeds stored under .nBlocks and .stimuliSeed.
%
%   Those last two names are the regression B2.6 records: every consumer of
%   this settings file — experiment.subjectExperimentFile,
%   experiment.loadStimuliCamouflage and
%   experiment.analysis.computeThreshold_texture_exponent — reads .nLevels and
%   .seeds, which this variant alone stops emitting. The settings file on disk
%   still has .nLevels, so it was written by an earlier version of this file.
%
%   The texture exponents are stored in a field named .alphas, which the shape-
%   exponent variant uses for a different quantity (a boundary shape
%   exponent). The local is named texture_exponents throughout this family to
%   keep the two apart; the field name is frozen on disk (zone 3, S3.10).
%
%   ml and cont keep their abbreviated names, unlike the base variant's
%   luminance/contrast, because the corrected names would equal the
%   'luminance' and 'contrast' field-name string literals in the struct call
%   below — a rename Stage 1 cannot make.
%
%   This is one of five near-duplicate sessionSettings variants; S3.3
%   collapses them.
%
%   See also experiment.SETUPEXPERIMENT_TEXTURE_EXPONENT,
%   experiment.GENERATE_CAMOUFLAGE_STIMULI_TEXTURE_EXPONENT, experiment.SESSIONSETTINGS.

    stimulusIntervalMs = 200;
    responseInvervalMs = 1000;
    fixationIntervalMs = 100;
    blankIntervalMs = 0;

    monitorMaxPix = 255;
    bgPixVal = ml*255;
    monitor_brightness = 50;
    monitor_contrast = 100;

    nBlocks = length(texture_exponents);
    nTrials = 30;
    nSessions = 4;

    stimPosDeg = zeros(nTrials, nBlocks, nSessions, 2);
    fixPosDeg = zeros(nTrials, nBlocks, nSessions, 2);

    loadSessionStimuli = @experiment.loadStimuliCamouflage;
    pTarget = .5;

    % generate stimuli
    bTargetPresent = logical(experiment.generateTargetPresentMatrix(nTrials, nBlocks, ...
        nSessions, pTarget));
    [stimuli, stimuliSeed, edgePowers, pClipped] = ...
        experiment.generate_camouflage_stimuli_texture_exponent(texture_exponents, nTrials, ...
        nSessions, bg_size, target_radius, ml, cont, bTargetPresent);

    SessionSettings = struct(...
        'exp_type', exp_type,...
        'texture_params', texture,...
        'alphas', texture_exponents,...
        'luminance', ml,...
        'contrast', cont,...
        'target_radius', target_radius,...
        'stimulus_size', bg_size,...
        'monitor_distance', monitor_distance,...
        'nBlocks', nBlocks,...
        'nTrials', nTrials,...
        'nSessions', nSessions, ...
        'pTarget', pTarget,...
        'loadSessionStimuli', loadSessionStimuli, ...
        'bTargetPresent', bTargetPresent,...
        'edgePowers', edgePowers,...
        'stimuliSeed', stimuliSeed,...
        'stimuli', stimuli,...
        'pClipped', pClipped,...
        'moniter_brightness', monitor_brightness,...
        'monitor_contrast', monitor_contrast,...
        'stimPosDeg', stimPosDeg, ...
        'fixPosDeg', fixPosDeg,...
        'monitorMaxPix', monitorMaxPix, ...
        'bgPixVal', bgPixVal, ...
        'stimulusIntervalMs', stimulusIntervalMs,...
        'responseIntervalMs', responseInvervalMs, ...
        'fixationIntervalMs', fixationIntervalMs,...
        'blankIntervalMs', blankIntervalMs...
        );
end
