function SessionSettings = session_settings_all(luminance, contrast, stimulus_size, ...
    target_radius, ppd)
% SESSION_SETTINGS_ALL  Settings and stimuli for the all-textures experiment variant.
%   SessionSettings = experiment.session_settings_all(luminance, contrast, ...
%       stimulus_size, target_radius, ppd)
%
%   Variant of experiment.session_settings whose levels are textures rather
%   than edge-power bands. Loads the texture list, generates the same number
%   of trials for each texture, and shuffles them into the usual
%   trial/level/session layout. There is no edge-power file, so no
%   edge_power_block_edges and no stim_edge_powers; instead the per-trial texture is
%   recorded in .textures.
%
%   Inputs
%     luminance     - mean luminance, normalised, in [0, 1].
%     contrast      - RMS contrast, dimensionless fraction.
%     stimulus_size - stimulus side, in pixels.
%     target_radius - target radius, in pixels.
%     ppd           - pixels per degree. Stored in the .monitor_distance
%                     field, which is a misnomer shared with the base variant
%                     (B3.8); here at least the local says what it holds.
%
%   Output
%     SessionSettings - the ExpSettings struct, as in experiment.
%                       session_settings but with .textures, .nTex and
%                       .nTrials_eachtx in place of the edge-power fields.
%
%   The trial count is derived, not chosen: n_tex textures x 40 trials each,
%   redistributed over 10 levels and 4 sessions.
%
%   Every field name here is serialised into exp_settings.mat, so none may be
%   renamed without a migration (zone 3, S3.10) — including the misspelled
%   .moniter_brightness and the local response_interval_ms that feeds
%   .responseIntervalMs, which keeps its typo because the corrected name would
%   equal a string literal in this file.
%
%   This is one of five near-duplicate session_settings variants; S3.3
%   collapses them.
%
%   See also experiment.SET_UP_EXPERIMENT_ALL, experiment.GENERATE_CAMOUFLAGE_STIMULI_ALL,
%   experiment.SESSION_SETTINGS.

    stimulus_interval_ms = 200;
    response_interval_ms = 1000;
    fixation_interval_ms = 100;
    blank_interval_ms = 0;

    monitor_max_pix = 255;
    bg_pix_val = luminance*255;
    monitor_brightness = 50;
    monitor_contrast = 100;

    % load texture list
    load('exp_files/all/texture_list.mat');
    n_tex = length(texture_list);

    n_trials_eachtx = 40;

    n_levels = 10;
    n_sessions = 4;
    n_trials = n_tex*n_trials_eachtx/(n_levels*n_sessions);

    stim_pos_deg = zeros(n_trials, n_levels, n_sessions, 2);
    fix_pos_deg = zeros(n_trials, n_levels, n_sessions, 2);

    load_session_stimuli = @experiment.load_stimuli_camouflage;
    p_target = .5;

    % generate stimuli
    [stimuli, textures, seeds, b_target_present, p_clipped] = ...
        experiment.generate_camouflage_stimuli_all(texture_list, n_tex, n_trials_eachtx, ...
        n_trials, n_levels, n_sessions, stimulus_size, target_radius, luminance, contrast);

    SessionSettings = struct(...
        'exp_type', 'all',...
        'textures', textures,...
        'luminance', luminance,...
        'contrast', contrast,...
        'target_radius', target_radius,...
        'stimulus_size', stimulus_size,...
        'monitor_distance', ppd,...
        'nTrials_eachtx', n_trials_eachtx,...
        'nLevels', n_levels,...
        'nTex', n_tex,...
        'nTrials', n_trials,...
        'nSessions', n_sessions, ...
        'pTarget', p_target,...
        'loadSessionStimuli', load_session_stimuli, ...
        'bTargetPresent', b_target_present,...
        'seeds', seeds,...
        'stimuli', stimuli,...
        'pClipped', p_clipped,...
        'moniter_brightness', monitor_brightness,...
        'monitor_contrast', monitor_contrast,...
        'stimPosDeg', stim_pos_deg, ...
        'fixPosDeg', fix_pos_deg,...
        'monitorMaxPix', monitor_max_pix, ...
        'bgPixVal', bg_pix_val, ...
        'stimulusIntervalMs', stimulus_interval_ms,...
        'responseIntervalMs', response_interval_ms, ...
        'fixationIntervalMs', fixation_interval_ms,...
        'blankIntervalMs', blank_interval_ms...
        );
end
